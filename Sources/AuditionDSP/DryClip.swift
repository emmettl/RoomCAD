import Foundation

/// A dry (ideally anechoic) mono recording to play through a room.
public struct DryClip: Equatable, Sendable, Identifiable {
    public var id: String
    public var name: String
    /// Source, author and licence, shown wherever the clip is offered.
    public var credit: String
    public var samples: [Float]
    public var sampleRate: Int

    /// Clips are scaled to this peak so they play at similar levels.
    public static let peak: Float = 0.5
    /// Longer files are cut to this many seconds.
    public static let maximumDuration = 60.0

    public init(id: String, name: String, credit: String, samples: [Float], sampleRate: Int) {
        self.id = id
        self.name = name
        self.credit = credit
        self.samples = Self.normalized(samples)
        self.sampleRate = sampleRate
    }

    public var duration: Double { Double(samples.count) / Double(sampleRate) }

    static func normalized(_ samples: [Float]) -> [Float] {
        let largest = samples.reduce(Float(0)) { max($0, abs($1)) }
        guard largest > 0 else { return samples }
        return samples.map { $0 * peak / largest }
    }
}

// MARK: - Test signals

extension DryClip {
    /// Half a second of pink noise and then silence: the classic way to hear a decay.
    public static func noiseBurst(sampleRate: Int) -> DryClip {
        var random = SplitMix(seed: 1)
        let burst = Int(0.5 * Double(sampleRate))
        let ramp = Int(0.005 * Double(sampleRate))
        // Paul Kellet's economy pink-noise filter.
        var (b0, b1, b2) = (0.0, 0.0, 0.0)
        var samples = [Float](repeating: 0, count: burst + 2 * sampleRate)
        for i in 0..<burst {
            let white = random.nextSigned()
            b0 = 0.99765 * b0 + white * 0.0990460
            b1 = 0.96300 * b1 + white * 0.2965164
            b2 = 0.57000 * b2 + white * 1.0526913
            let edge = min(1, Double(min(i, burst - 1 - i)) / Double(ramp))
            samples[i] = Float((b0 + b1 + b2 + white * 0.1848) * edge)
        }
        return DryClip(
            id: "noise-burst", name: "Noise burst", credit: "Generated by RoomCAD", samples: samples,
            sampleRate: sampleRate)
    }

    /// Single clicks a second apart: each shows the early reflections and the decay.
    public static func clicks(sampleRate: Int) -> DryClip {
        var samples = [Float](repeating: 0, count: 4 * sampleRate)
        for second in 0..<3 {
            // A two-sample click keeps the spectrum broad without being harsh.
            samples[second * sampleRate + sampleRate / 10] = 1
            samples[second * sampleRate + sampleRate / 10 + 1] = -0.5
        }
        return DryClip(
            id: "clicks", name: "Clicks", credit: "Generated by RoomCAD", samples: samples,
            sampleRate: sampleRate)
    }
}

/// Deterministic generator so test signals are identical on every run.
struct SplitMix {
    var state: UInt64

    init(seed: UInt64) { state = seed }

    mutating func next() -> UInt64 {
        state &+= 0x9E37_79B9_7F4A_7C15
        var z = state
        z = (z ^ (z >> 30)) &* 0xBF58_476D_1CE4_E5B9
        z = (z ^ (z >> 27)) &* 0x94D0_49BB_1331_11EB
        return z ^ (z >> 31)
    }

    /// Uniform in [-1, 1).
    mutating func nextSigned() -> Double {
        Double(next() >> 11) / Double(1 << 52) - 1
    }
}
